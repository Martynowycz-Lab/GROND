# Output multipliers of LIST 4 tried in turn; a larger one keeps more digits of weak reflections in the .fcf.
FCF_MULTIPLIERS = (1000.0, 100.0, 10.0, 1.0)
_CYCLE_RE = re.compile(r"^(\s*)(L\.S\.|LS|CGLS)(?=\s|$)(.*)$", flags=re.IGNORECASE)
_DATA_PARAMETERS_RE = re.compile(r"for\s+(\d+)\s+data and\s+(\d+)\s*/\s*(\d+)\s+parameters")
_FLOAT_RE = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[Ee][-+]?\d+)?")
# Records whose values are refined overall parameters (free variables, extinction, batch scales, solvent).
OVERALL_RECORDS = frozenset({"FVAR", "EXTI", "BASF", "SWAT"})
# SHELXL stores parameters in single precision; a value written back may differ by this relative amount.
SINGLE_PRECISION_RELATIVE = 2.0**-22
# SHELXL constrains the coordinates and Uij of an atom on a special position to its site symmetry and, at L.S. 0 as in
# every cycle, re-derives the tied parameters from the values it reads.  A .res carries them rounded to the digits
# SHELXL writes (6 decimals for coordinates, 5 for Uij), so a re-derived value can differ from the written one by one
# unit of that last digit: for example U13 = 2 U23 on a two-fold axis, where a written U23 of -0.01205 gives
# U13 -0.02410 against a written -0.02411.  The same reasoning as the work-statistics print-rounding rule
# (grond.validation.endpoint_free.WORK_STATISTICS_RULE).
SPECIAL_POSITION_ALLOWED_UNITS = 1
MODEL_UNCHANGED_RULE_TEXT = (
    "every atom occupancy and displacement parameter, coordinates outside AFIX riding/rigid groups, and every overall "
    "parameter (FVAR, EXTI, BASF, SWAT) comes "
    "back from L.S. 0 within SHELXL's single-precision storage (relative 2^-22), except the coordinates and Uij that "
    "the site symmetry of an atom on a special position ties (SHELXL re-derives them from the written values): each "
    "of those may differ by one unit of its last written digit (0.000001 for coordinates, 0.00001 for Uij); riding "
    "hydrogen coordinates are regenerated by SHELXL and reported separately"
)
# Names of the numeric fields of an atom line after the SFAC number: coordinates, sof, then Uij (or Uiso).
_ATOM_FIELDS = ("x", "y", "z", "sof", "U11", "U22", "U33", "U23", "U13", "U12")
_ISOTROPIC_FIELDS = ("x", "y", "z", "sof", "Uiso")
# The (i, j) tensor element of each SHELXL Uij, in the atom line's order U11 U22 U33 U23 U13 U12.
_UIJ_ELEMENTS = ((0, 0), (1, 1), (2, 2), (1, 2), (0, 2), (0, 1))
# Instruction keywords that can never be atom names in the atom list of a .res.
_INSTRUCTIONS = frozenset(
    {
        "TITL", "CELL", "ZERR", "LATT", "SYMM", "SFAC", "DISP", "UNIT", "LAUE", "REM", "MORE", "TIME", "END", "HKLF",
        "OMIT", "SHEL", "BASF", "TWIN", "EXTI", "SWAT", "HOPE", "MERG", "SPEC", "RESI", "MOVE", "ANIS", "AFIX", "HFIX",
        "FRAG", "FEND", "EXYZ", "EADP", "EQIV", "CONN", "PART", "BIND", "FREE", "DFIX", "DANG", "BUMP", "SAME", "SADI",
        "CHIV", "FLAT", "DELU", "SIMU", "DEFS", "ISOR", "NCSY", "SUMP", "L.S.", "CGLS", "BLOC", "DAMP", "STIR", "WGHT",
        "FVAR", "BOND", "CONF", "MPLA", "RTAB", "HTAB", "LIST", "ACTA", "SIZE", "TEMP", "WPDB", "FMAP", "GRID", "PLAN",
        "MOLE", "RIGU", "XNPD", "ABIN", "ANSC", "ANSR", "NEUT", "PRIG", "TWST", "WIGL",
    }
)


def _first_token(line: str) -> str:
    """Return the first word of a line in upper case, or an empty string."""

    parts = line.strip().split()
    return parts[0].upper() if parts else ""


def zero_cycle_ins_text(
    res_text: str,
    *,
    wght_line: str | None = None,
    fcf_multiplier: float = FCF_MULTIPLIERS[0],
    hklf_scale: float | None = None,
    free_flag: int | None = None,
) -> str:
    """The .ins of a zero-cycle scoring run of a refined .res: every instruction kept except the ones below.

    L.S./CGLS get 0 cycles (other tokens kept; ``free_flag`` sets the free-R flag nrf, SHELXL's second L.S.
    token: reflections with that value in columns 29-32 are the free set); LIST becomes ``LIST 4 <fcf_multiplier>``;
    ACTA is dropped (no CIF of
    a scoring run); ``wght_line`` replaces the active WGHT record verbatim when given; ``hklf_scale`` multiplies
    the scale S of the HKLF record (other HKLF tokens, a reindexing matrix included, are kept).  Everything after
    END (SHELXL's suggested WGHT, difference peaks) is dropped.
    """

    out: list[str] = []
    saw_cycles = saw_list = saw_wght = saw_hklf = False
    for line in res_text.splitlines():
        head = _first_token(line)
        if Q_PEAK_RE.match(line.strip()):
            continue
        if head == "ACTA":
            continue
        match = _CYCLE_RE.match(line)
        if match:
            indent, command, tail = match.groups()
            rest = tail.split() or ["0"]
            rest[0] = "0"
            if free_flag is not None:
                rest[1:2] = [str(int(free_flag))]
            line = f"{indent}{command} {' '.join(rest)}"
            saw_cycles = True
        elif head == "LIST":
            if saw_list:
                continue
            line = f"LIST 4 {float(fcf_multiplier):g}"
            saw_list = True
        elif head == "WGHT" and wght_line is not None:
            if saw_wght:
                continue
            line = str(wght_line).strip()
            saw_wght = True
        elif head == "HKLF":
            parts = line.split()
            if hklf_scale is not None:
                scale = float(parts[2]) if len(parts) > 2 else 1.0
                parts = [parts[0], parts[1] if len(parts) > 1 else "4", f"{scale * float(hklf_scale):.10g}", *parts[3:]]
            line = " ".join(parts)
            saw_hklf = True
        if head == "FVAR":
            if not saw_cycles:
                out.append("L.S. 0" if free_flag is None else f"L.S. 0 {int(free_flag)}")
                saw_cycles = True
            if not saw_list:
                out.append(f"LIST 4 {float(fcf_multiplier):g}")
                saw_list = True
            if wght_line is not None and not saw_wght:
                out.append(str(wght_line).strip())
                saw_wght = True
        out.append(line)
        if head == "END":
            break
    if not saw_hklf:
        raise ValueError("the refined model has no HKLF instruction")
    if not saw_cycles:
        raise ValueError("the refined model has no FVAR instruction to place L.S. 0 before")
    return "\n".join(out).rstrip() + "\n"


def active_wght_line(text: str) -> str | None:
    """The active (pre-END) WGHT record of a SHELXL .ins/.res, verbatim."""

    for line in text.splitlines():
        head = _first_token(line)
        if head == "END":
            return None
        if head == "WGHT":
            return line.strip()
    return None


def read_list4_fcf(path: Path) -> dict[str, object]:
    """h, k, l, Fc^2, Fo^2, sigma(Fo^2) and status of a LIST 4 .fcf, divided by its F-squared multiplier."""

    text = Path(path).read_text(errors="replace")
    multiplier = 1.0
    match = re.search(r"_shelx_F_squared_multiplier\s+([-+0-9.Ee]+)", text)
    if match:
        multiplier = float(match.group(1))
    list_code = re.search(r"_shelx_refln_list_code\s+(\d+)", text)
    if not list_code or int(list_code.group(1)) != 4:
        raise ValueError(f"{path} is not a LIST 4 .fcf")
    rows, flags = [], []
    in_loop = False
    for line in text.splitlines():
        if line.strip() == "_refln_observed_status":
            in_loop = True
            continue
        if not in_loop:
            continue
        parts = line.split()
        if len(parts) < 7:
            continue
        if any("*" in part for part in parts[:6]):
            raise OverflowError(f"{path}: overflowed .fcf field in {line!r}")
        rows.append([float(value) for value in parts[:6]])
        flags.append(parts[6])
    if not rows:
        raise ValueError(f"{path}: no reflections in the .fcf")
    data = np.asarray(rows, dtype=float)
    scale = 1.0 / multiplier if multiplier > 0.0 else 1.0
    return {
        "hkl": data[:, :3].astype(int),
        "fc2": data[:, 3] * scale,
        "fo2": data[:, 4] * scale,
        "sigma": data[:, 5] * scale,
        "status": np.asarray(flags),
        "multiplier": multiplier,
    }


def shelxl_weights(fo2: np.ndarray, fc2: np.ndarray, sigma: np.ndarray, terms: list[float]) -> np.ndarray:
    """SHELXL weights w = 1/[sigma^2 + (aP)^2 + bP], P = f max(Fo^2, 0) + (1 - f) Fc^2 (c = d = e = 0 only)."""

    a = float(terms[0]) if terms else 0.1
    b = float(terms[1]) if len(terms) > 1 else 0.0
    c, d, e = (float(terms[i]) if len(terms) > i else 0.0 for i in (2, 3, 4))
    f = float(terms[5]) if len(terms) > 5 else 1.0 / 3.0
    if c != 0.0 or d != 0.0 or e != 0.0:
        raise ValueError(f"WGHT terms c, d, e must be zero for the .fcf recomputation, got {terms}")
    p = f * np.maximum(fo2, 0.0) + (1.0 - f) * fc2
    return 1.0 / (sigma * sigma + (a * p) ** 2 + b * p)


def fixed_scale_statistics(
    fo2: np.ndarray, fc2: np.ndarray, sigma: np.ndarray, wght_terms: list[float], n_parameters: int | None
) -> dict[str, object]:
    """R1(Fo > 4sig(Fo)), R1(all), wR2, sum w D^2 and GooF (N - P and N denominators) of reflections on one scale.

    Fo > 4 sigma(Fo) is Fo^2 > 2 sigma(Fo^2) with sigma(Fo) = sigma(Fo^2) / (2 Fo), SHELXL's rule.
    """

    fo2, fc2, sigma = (np.asarray(values, dtype=float) for values in (fo2, fc2, sigma))
    n = int(fo2.size)
    out: dict[str, object] = {"N_all": n}
    if n == 0:
        return out
    fo = np.sqrt(np.maximum(fo2, 0.0))
    fc = np.sqrt(np.maximum(fc2, 0.0))
    gt = fo2 > 2.0 * sigma
    w = shelxl_weights(fo2, fc2, sigma, wght_terms)
    delta2 = float(np.sum(w * (fo2 - fc2) ** 2))
    out.update(
        {
            "N_gt": int(np.count_nonzero(gt)),
            "R1_gt": float(np.sum(np.abs(fo - fc)[gt]) / np.sum(fo[gt])) if np.any(gt) else None,
            "R1_all": float(np.sum(np.abs(fo - fc)) / np.sum(fo)),
            "sum_abs_fo_minus_fc": float(np.sum(np.abs(fo - fc))),
            "sum_fo": float(np.sum(fo)),
            "wR2_all": float(math.sqrt(delta2 / float(np.sum(w * fo2 * fo2)))),
            "sum_w_delta2": delta2,
            "GooF_n": float(math.sqrt(delta2 / n)),
            "GooF_n_minus_p": float(math.sqrt(delta2 / (n - int(n_parameters))))
            if n_parameters is not None and n > int(n_parameters)
            else None,
        }
    )
    return out


_FREE_R1_RE = re.compile(r"R1\(Free\) =\s*([0-9.]+) for\s+(\d+) Fo > 4sig\(Fo\) and\s+([0-9.]+) for all\s+(\d+) data")
_FREE_SUMS_RE = re.compile(
    r"Nfree\((I>2sig|all)\)\s+(\d+)\s+Sum\|Fo-Fc\|\s+([-+0-9.Ee]+)\s+Sum\(Fo\)\s+([-+0-9.Ee]+)"
)


def free_listing_statistics(text: str) -> dict[str, object]:
    """SHELXL's printed free-set statistics: R1(Free) and the Nfree Sum|Fo-Fc| / Sum(Fo) lines (last cycle)."""

    out: dict[str, object] = {}
    match = _FREE_R1_RE.findall(text)
    if match:
        r1_gt, n_gt, r1_all, n_all = match[-1]
        out.update({"R1_gt": float(r1_gt), "N_gt": int(n_gt), "R1_all": float(r1_all), "N_all": int(n_all)})
    for kind, count, abs_sum, fo_sum in _FREE_SUMS_RE.findall(text):
        key = "gt" if kind.startswith("I") else "all"
        out[f"sums_{key}"] = {"N": int(count), "sum_abs_fo_minus_fc": float(abs_sum), "sum_fo": float(fo_sum)}
    return out


def _joined_lines(text: str) -> list[str]:
    """Return the lines of a SHELX file with each ``=`` continuation joined to its record."""

    lines: list[str] = []
    pending = ""
    for raw in text.splitlines():
        line = pending + " " + raw.strip() if pending else raw
        if line.rstrip().endswith("="):
            pending = line.rstrip()[:-1]
            continue
        pending = ""
        lines.append(line)
    return lines


def _atom_records(text: str) -> tuple[dict[str, tuple[list[float], bool, list[str]]], list[float]]:
    """Atom identity -> (numeric parameters, regenerated coordinates, written parameters), and overall parameters.

    Residue, disorder part and occurrence distinguish repeated labels, as in feedback_trajectory.atom_xyz.
    """

    lines = _joined_lines(text)
    atoms: dict[str, tuple[list[float], bool, list[str]]] = {}
    overall: list[float] = []
    coordinates_regenerated = False
    started = False
    residue, part = "", "0"
    occurrences: dict[str, int] = {}
    for line in lines:
        parts = line.split()
        if not parts:
            continue
        head = parts[0].upper()
        if head in {"HKLF", "END"}:
            break
        if head in OVERALL_RECORDS:
            started = started or head == "FVAR"
            overall.extend(float(value) for value in parts[1:] if _FLOAT_RE.fullmatch(value))
            continue
        if not started:
            continue
        if head == "RESI":
            residue = "" if parts[1:] in ([], ["0"]) else " ".join(parts[1:]).upper()
            continue
        if head == "PART":
            part = parts[1] if len(parts) > 1 else "0"
            continue
        if head == "AFIX":
            code = int(parts[1]) if len(parts) > 1 and parts[1].lstrip("-").isdigit() else 0
            # AFIX n=1 fixes coordinates; n=2 leaves them free. Neither regenerates them as a riding/rigid group.
            coordinates_regenerated = code % 10 in {3, 4, 5, 6, 7, 8, 9}
            continue
        if head in _INSTRUCTIONS or len(parts) < 5 or not parts[1].isdigit():
            continue
        try:
            values = [float(value) for value in parts[2:]]
        except ValueError:
            continue
        key = head if not residue and part == "0" else f"{head}|RESI {residue}|PART {part}"
        seen = occurrences.get(key, 0)
        occurrences[key] = seen + 1
        atoms[key if seen == 0 else f"{key}#{seen}"] = (values, coordinates_regenerated, parts[2:])
    return atoms, overall


def _nonzero_columns(blocks: list[np.ndarray]) -> list[bool]:
    """Which columns of the stacked matrices have an entry that is not zero (1e-6: the entries are O(1) or exact 0)."""

    stacked = np.vstack(blocks)
    return [bool(value) for value in np.max(np.abs(stacked), axis=0) > 1e-6]


def special_position_parameters(text: str) -> dict[str, dict[str, object]]:
    """The atoms of a SHELX model that sit on a special position: name -> site-symmetry order and tied parameters.

    The operations are those of LATT and SYMM (grond.bloch.model.shelx_symmetry_records, centring and inversion
    included).  An operation (R, t) belongs to an atom's site symmetry when it maps the atom onto itself within
    SITE_SYMMETRY_TOLERANCE_FRACTIONAL (the rule GROND's own structure factors use, bloch.model.unique_symmetry_mates).
    A coordinate is tied when a site operation moves it on its own ((R - 1) has a non-zero column), a Uij when U ->
    M U M^T - U with M = N^-1 R N, N = diag(a*, b*, c*), does (SHELXL's Uij refer to the reciprocal axes).  A model
    whose CELL, LATT, SYMM or coordinates cannot be read has no special positions here (the strict rule then applies).
    """

    lines = _joined_lines(text)
    cell, latt, symm, free_variables = None, 1, [], []
    for line in lines:
        parts = line.split()
        head = parts[0].upper() if parts else ""
        if head in {"HKLF", "END"}:
            break
        try:
            if head == "CELL" and len(parts) >= 8:
                cell = tuple(float(value) for value in parts[2:8])
            elif head == "LATT" and len(parts) > 1:
                latt = int(float(parts[1]))
            elif head == "SYMM":
                symm.append(line.strip()[4:].strip())
            elif head == "FVAR":
                free_variables.extend(float(value) for value in parts[1:] if _FLOAT_RE.fullmatch(value))
        except ValueError:
            return {}
    if cell is None:
        return {}
    try:
        operations = [(np.asarray(op["rot"], dtype=float), np.asarray(op["trans"], dtype=float))
                      for op in shelx_symmetry_records(latt, symm)]
        scale = np.diag(reciprocal_lengths(cell))
    except (ValueError, RuntimeError):
        return {}
    inverse_scale = np.linalg.inv(scale)
    atoms, _overall = _atom_records(text)
    out: dict[str, dict[str, object]] = {}
    for name, (values, _constrained, _tokens) in atoms.items():
        try:
            xyz = np.asarray([shelx_parameter(value, free_variables, field=f"{name} coordinate") for value in values[:3]])
        except ValueError:
            continue
        site = []
        for rotation, translation in operations:
            delta = rotation @ xyz + translation - xyz
            if np.allclose(rotation, np.eye(3)) or np.max(np.abs(delta - np.rint(delta))) > SITE_SYMMETRY_TOLERANCE_FRACTIONAL:
                continue
            site.append(rotation)
        if not site:
            continue
        tied = [field for field, flag in zip(("x", "y", "z"), _nonzero_columns([r - np.eye(3) for r in site]), strict=True) if flag]
        if len(values) >= 10:
            blocks = []
            for rotation in site:
                m = inverse_scale @ rotation @ scale
                columns = []
                for i, j in _UIJ_ELEMENTS:
                    unit = np.zeros((3, 3))
                    unit[i, j] = unit[j, i] = 1.0
                    moved = m @ unit @ m.T - unit
                    columns.append([moved[a, b] for a, b in _UIJ_ELEMENTS])
                blocks.append(np.asarray(columns).T)
            tied += [field for field, flag in zip(_ATOM_FIELDS[4:], _nonzero_columns(blocks), strict=True) if flag]
        out[name] = {"site_symmetry_order": len(site) + 1, "tied_parameters": tied}
    return out


def _written_decimals(token: str) -> int:
    """Digits after the decimal point of a written number (0 without one)."""

    mantissa = token.lower().split("e")[0]
    return len(mantissa.split(".")[1]) if "." in mantissa else 0


def _relative(x: float, y: float) -> float:
    """Return abs(x - y) / abs(x), with the denominator at least 1e-12."""

    return abs(x - y) / max(abs(x), 1e-12)


def model_parameter_changes(before_text: str, after_text: str) -> dict[str, object]:
    """Largest change of any atom parameter and overall parameter (FVAR, EXTI, BASF, SWAT) between a zero-cycle
    input and its output .res, and whether that is no change (MODEL_UNCHANGED_RULE_TEXT).

    Coordinates in AFIX riding/rigid groups are regenerated by SHELXL and reported separately; occupancies and ADPs
    are still compared.  ``unchanged`` allows the relative rounding of SHELXL's single-precision
    storage (EXTI 4351.925293 is written back as 4351.924805) and, for the coordinates and Uij that the site symmetry
    of an atom on a special position ties (special_position_parameters), one unit of the last written digit; every
    such parameter that changed is listed with its written values in ``special_position_changes``.
    """

    before, overall_before = _atom_records(before_text)
    after, overall_after = _atom_records(after_text)
    invalid = sorted({name for atoms in (before, after) for name, (values, _constrained, _tokens) in atoms.items()
                      if not all(math.isfinite(value) for value in values)})
    special = special_position_parameters(before_text) if not invalid else {}
    free_change = free_relative = constrained_change = 0.0
    special_changes: list[dict[str, object]] = []
    missing = sorted(set(before) ^ set(after))
    for name, (values, constrained, tokens) in before.items():
        if name not in after or name in invalid:
            continue
        other, other_tokens = after[name][0], after[name][2]
        if len(other) != len(values):
            missing.append(name)
            continue
        change = max((abs(x - y) for x, y in zip(values, other, strict=True)), default=0.0)
        if constrained:
            constrained_change = max(constrained_change, change)
        fields = _ATOM_FIELDS if len(values) >= 10 else _ISOTROPIC_FIELDS
        tied = set((special.get(name) or {}).get("tied_parameters") or ())
        for index, (x, y) in enumerate(zip(values, other, strict=True)):
            if constrained and index < 3:
                continue
            field = fields[index] if index < len(fields) else f"field_{index + 3}"
            if field in tied:
                if x == y:
                    continue
                decimals = max(_written_decimals(tokens[index]), _written_decimals(other_tokens[index]))
                units = abs(round(x * 10**decimals) - round(y * 10**decimals))
                special_changes.append({
                    "atom": name, "parameter": field, "before": x, "after": y,
                    "before_written": tokens[index], "after_written": other_tokens[index], "written_decimals": decimals,
                    "difference_units_of_last_digit": int(units),
                    "allowed_units_of_last_digit": SPECIAL_POSITION_ALLOWED_UNITS,
                    "site_symmetry_order": special[name]["site_symmetry_order"],
                })
                continue
            free_change = max(free_change, abs(x - y))
            free_relative = max(free_relative, _relative(x, y))
    if len(overall_before) == len(overall_after):
        pairs = list(zip(overall_before, overall_after, strict=True))
        overall_change = max((abs(x - y) for x, y in pairs), default=0.0)
        overall_relative = max((_relative(x, y) for x, y in pairs), default=0.0)
    else:
        overall_change = overall_relative = float("inf")
    special_units = max((int(item["difference_units_of_last_digit"]) for item in special_changes), default=0)
    return {
        "rule": MODEL_UNCHANGED_RULE_TEXT,
        "atoms": len(before),
        "max_abs_change_unconstrained_atoms": free_change,
        "max_relative_change_unconstrained_atoms": free_relative,
        "max_abs_change_constrained_atoms": constrained_change,
        "max_abs_change_overall": overall_change,
        "max_relative_change_overall": overall_relative,
        "overall_parameters": len(overall_before),
        "atoms_missing_or_reshaped": sorted(set(missing)),
        "atoms_with_nonfinite_parameters": invalid,
        "special_position_atoms": special,
        "special_position_changes": special_changes,
        "max_units_special_position_changes": special_units,
        "unchanged": bool(
            free_relative <= SINGLE_PRECISION_RELATIVE and overall_relative <= SINGLE_PRECISION_RELATIVE
            and not missing and not invalid
            and special_units <= SPECIAL_POSITION_ALLOWED_UNITS
        ),
    }


def _close(a: object, b: object, tolerance: float, *, relative: bool = False) -> bool | None:
    """Return whether a and b agree within ``tolerance`` (relative to a when ``relative``), or
    None when either is missing.
    """

    if a is None or b is None:
        return None
    scale = max(abs(float(a)), 1e-30) if relative else 1.0
    return abs(float(a) - float(b)) <= tolerance * scale


def _hklf_scale_of(ins_text: str) -> float:
    """Return the intensity scale (second HKLF argument) of the first HKLF line, or 1."""

    for line in ins_text.splitlines():
        parts = line.split()
        if parts and parts[0].upper() == "HKLF":
            return float(parts[2]) if len(parts) > 2 else 1.0
    return 1.0


def run_zero_cycle(
    directory: Path,
    stem: str,
    *,
    res: Path,
    hkl: Path,
    shelxl: str,
    wght_line: str | None = None,
    hklf_scale: float | None = None,
    free_flag: int | None = None,
    timeout: int = 1800,
) -> dict[str, object]:
    """Score ``res`` on ``hkl`` with L.S. 0 in ``directory`` (files ``stem.*``); returns the statistics record.

    With ``free_flag`` (SHELXL's free-R flag, -1) the reflections carrying it in columns 29-32 are the free set:
    ``work`` holds SHELXL's statistics of the other reflections (as printed, GooF with N - P), ``free`` the free
    set's R1(Free) as printed and its wR2 and GooF (N denominator) recomputed on the model's scale from the .fcf.
    """

    exe = str(shelxl or shutil.which("shelxl") or "")
    if not exe or ("/" in exe and not Path(exe).is_file()):
        return {"status": "missing_shelxl", "executable": exe}
    directory = Path(directory)
    target_hkl = directory / f"{stem}.hkl"
    target_ins = directory / f"{stem}.ins"
    outputs = [directory / f"{stem}{suffix}" for suffix in (".lst", ".fcf", ".res")]
    written_paths = [target_hkl, target_ins, *outputs]
    if (Path(res).resolve() in {path.resolve() for path in written_paths}
            or Path(hkl).resolve() in {path.resolve() for path in [target_ins, *outputs]}):
        raise ValueError("zero-cycle outputs would overwrite an input file; use a separate scoring directory")
    directory.mkdir(parents=True, exist_ok=True)
    if Path(hkl).resolve() != target_hkl.resolve():
        shutil.copyfile(hkl, target_hkl)
    res_text = Path(res).read_text(errors="replace")
    record: dict[str, object] = {"res": str(Path(res).resolve()), "hkl": str(target_hkl.resolve()), "ls_cycles": 0,
                                 "free_flag": free_flag}
    fcf: dict[str, object] | None = None
    fcf_error = ""
    ins_text = ""
    lst_text = ""
    listing: dict[str, object] = {}
    for multiplier in FCF_MULTIPLIERS:
        # Each attempt must produce its own outputs, including retries at a smaller LIST multiplier.
        for path in outputs:
            path.unlink(missing_ok=True)
        ins_text = zero_cycle_ins_text(
            res_text, wght_line=wght_line, fcf_multiplier=multiplier, hklf_scale=hklf_scale, free_flag=free_flag
        )
        target_ins.write_text(ins_text)
        proc = subprocess.run([exe, stem], cwd=directory, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
                              timeout=timeout)
        (directory / f"{stem}_shelxl.log").write_text(proc.stdout)
        record["returncode"] = proc.returncode
        missing = [path.name for path in outputs if not path.is_file()]
        if missing:
            record.update(status="shelxl_failed", missing_outputs=missing)
            return record
        lst_path = directory / f"{stem}.lst"
        listing = parse_lst(lst_path)
        lst_text = lst_path.read_text(errors="replace") if lst_path.is_file() else ""
        match = _DATA_PARAMETERS_RE.findall(lst_text)
        if match:
            listing["parameters"] = int(match[-1][2])
            listing["restraints"] = int(match[-1][1])
        if proc.returncode != 0 or listing.get("status") != "ok":
            record.update(status="shelxl_failed", listing_status=listing.get("status"))
            return record
        try:
            fcf = read_list4_fcf(directory / f"{stem}.fcf")
            break
        except OverflowError:
            continue
        except (OSError, ValueError) as exc:
            fcf_error = f"{type(exc).__name__}: {exc}"
            break
    parameters = listing.get("parameters")
    wght_terms = parse_shelx_wght_terms(active_wght_line(ins_text) or "WGHT 0.1")
    work: dict[str, object] = {
        "N_all": listing.get("N_all"),
        "N_gt": listing.get("N_gt"),
        "R1_gt": listing.get("R1_gt"),
        "R1_all": listing.get("R1_all"),
        "wR2_all": listing.get("wR2_all"),
        "GooF": listing.get("GooF") if listing.get("GooF") is not None and float(listing["GooF"]) < 99.99 else None,
        "GooF_definition": "SHELXL S = sqrt(sum w (Fo^2 - Fc^2)^2 / (N - P)), as the refinement reports it",
        "source": "SHELXL listing",
    }
    free_printed = free_listing_statistics(lst_text) if free_flag is not None else {}
    checks: dict[str, object] = {}
    free: dict[str, object] | None = None
    scale = 1.0
    if fcf is None:
        checks["fcf"] = fcf_error or "no .fcf"
    else:
        flags = np.asarray(fcf["status"])
        is_free = flags == "x" if free_flag is not None else np.zeros(flags.size, dtype=bool)
        used = flags == "o"
        all_sum = (free_printed.get("sums_all") or {}) if free_flag is not None else {}
        if free_flag is not None and all_sum and np.any(is_free):
            # the .fcf's Fo^2 and sigma(Fo^2) carry one rescale factor; SHELXL's free Sum(Fo) is on the model scale
            fcf_sum = float(np.sum(np.sqrt(np.maximum(np.asarray(fcf["fo2"])[is_free], 0.0))))
            scale = (float(all_sum["sum_fo"]) / fcf_sum) ** 2 if fcf_sum > 0.0 else float("nan")
        fo2 = np.asarray(fcf["fo2"], dtype=float) * scale
        sigma = np.asarray(fcf["sigma"], dtype=float) * scale
        fc2 = np.asarray(fcf["fc2"], dtype=float)
        work_fixed = fixed_scale_statistics(fo2[used], fc2[used], sigma[used], wght_terms, parameters)
        work["GooF_n"] = work_fixed.get("GooF_n")
        work["recomputed_from_fcf"] = work_fixed
        # The listing prints R1 and wR2 with four decimals and S with three: the .fcf recomputation must agree to that.
        checks["work_R1_gt"] = _close(work_fixed.get("R1_gt"), work.get("R1_gt"), 6e-5)
        checks["work_R1_all"] = _close(work_fixed.get("R1_all"), work.get("R1_all"), 6e-5)
        checks["work_wR2_all"] = _close(work_fixed.get("wR2_all"), work.get("wR2_all"), 6e-5)
        checks["work_GooF"] = _close(work_fixed.get("GooF_n_minus_p"), work.get("GooF"), 6e-4)
        checks["work_N_all"] = work_fixed.get("N_all") == work.get("N_all")
        if free_flag is not None:
            free_fixed = fixed_scale_statistics(fo2[is_free], fc2[is_free], sigma[is_free], wght_terms, parameters)
            free = {
                "N_all": free_printed.get("N_all"),
                "N_gt": free_printed.get("N_gt"),
                "R1_gt": free_printed.get("R1_gt"),
                "R1_all": free_printed.get("R1_all"),
                "wR2_all": free_fixed.get("wR2_all"),
                "GooF": free_fixed.get("GooF_n"),
                "GooF_definition": "sqrt(sum w (Fo^2 - Fc^2)^2 / N) on the model's scale (nothing was fitted to these reflections)",
                "sum_w_delta2": free_fixed.get("sum_w_delta2"),
                "source": "R1 and N: SHELXL listing R1(Free); wR2 and GooF: the .fcf of the same run on the model's scale",
                "shelxl_sums": {key: free_printed.get(key) for key in ("sums_gt", "sums_all")},
                "recomputed_from_fcf": free_fixed,
            }
            checks["free_rows_in_fcf"] = int(np.count_nonzero(is_free)) == free_printed.get("N_all")
            # SHELXL prints six digits; the .fcf rounding of weak reflections moves the recomputed sum by ~1e-5-1e-4
            checks["free_sum_abs_fo_minus_fc"] = _close(
                free_fixed.get("sum_abs_fo_minus_fc"), (free_printed.get("sums_all") or {}).get("sum_abs_fo_minus_fc"),
                2e-4, relative=True,
            )
            checks["free_R1_gt"] = _close(free_fixed.get("R1_gt"), free.get("R1_gt"), 6e-5)
            checks["free_R1_all"] = _close(free_fixed.get("R1_all"), free.get("R1_all"), 6e-5)
            checks["free_N_gt"] = (
                free_fixed.get("N_gt") is not None and free.get("N_gt") is not None
                and abs(int(free_fixed["N_gt"]) - int(free["N_gt"])) <= 1
            )
    ok = bool(checks) and all(value is not False and not isinstance(value, str) for value in checks.values())
    if free_flag is not None and (free is None or free.get("R1_all") is None):
        ok = False
    res_out = directory / f"{stem}.res"
    record.update(
        {
            "status": "ok" if ok else "listing_mismatch",
            "work": work,
            "free": free,
            "fcf_scale_to_model": scale,
            "fcf_multiplier": fcf.get("multiplier") if fcf else None,
            "checks": checks,
            "parameters": parameters,
            "restraints": listing.get("restraints"),
            "unique_reflections": listing.get("unique"),
            "wght": active_wght_line(ins_text),
            "hklf": next((line for line in ins_text.splitlines() if _first_token(line) == "HKLF"), None),
            "hklf_scale": _hklf_scale_of(ins_text),
            "model_changes": model_parameter_changes(ins_text, res_out.read_text(errors="replace"))
            if res_out.is_file()
            else {"unchanged": None},
        }
    )
    return record
