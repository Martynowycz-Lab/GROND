"""Zero-cycle SHELXL scoring of a refined model on its work reflections and on held-out (free) reflections.

``L.S. 0`` makes SHELXL compute Fc from the refined parameters without moving any (riding hydrogens are placed on
their parents first, as before every cycle).  The held-out reflections go into the same run with SHELXL's own
free-R flag (-1 in columns 29-32, ``L.S. 0 -1``), so one run reports the work statistics exactly as the refinement
did and R1(Free) at the model's own scale.  Two SHELXL behaviours are the reason for that design:

* a separate L.S. 0 run on the free reflections alone prints R1 at the model's scale, but its wR2 and GooF come
  with an overall scale refitted to those reflections, and the GooF divides by N - P (99.999 when N <= P);
* the LIST 4 .fcf rescales Fo^2 and sigma(Fo^2) by one least-squares factor of the file.

SHELXL prints R1 only for the free set.  Its wR2 and GooF are therefore recomputed from the .fcf of the same run
(``LIST 4 <multiplier>`` keeps enough digits): Fo^2 and sigma(Fo^2) are put back on the model's scale with the
factor that reproduces SHELXL's printed free Sum(Fo), the weights are the final WGHT, and the GooF of the free set
divides by N (no parameter was fitted to it).  The same recomputation of the work reflections must reproduce SHELXL's
printed work wR2 and GooF, and the free Sum|Fo-Fc| must reproduce SHELXL's: both are checked.
"""

